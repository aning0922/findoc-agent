import { test, expect } from '@playwright/test';
import { readFileSync, writeFileSync } from 'node:fs';
const out=process.env.UX_ARTIFACT_DIR!;
const seed=JSON.parse(readFileSync(`${process.env.D26_REPORT_SEED_DIR || `${out}/../seed`}/journey-proof.json`,'utf8'));
test('D26 actual report commit lost response, failed history read, v1/v2 and exact Markdown',async({page})=>{
  await page.route('**/src/main.tsx*',route=>route.fulfill({contentType:'text/javascript',body:'import "/tests/support/d20-entry.tsx";'}));
  const writes:any[]=[];page.on('request',r=>{if(r.method()==='POST')writes.push({url:r.url(),body:r.postDataJSON()});});
  await page.goto(`/reports?task=${seed.result.task_id}`);
  await page.getByRole('button',{name:'生成草稿',exact:true}).click();
  await expect(page.getByRole('article',{name:'报告草稿预览'})).toBeVisible();
  let saved:any;
  await page.route('**/api/reports',async route=>{if(route.request().method()!=='POST')return route.continue();const r=await route.fetch();expect(r.status()).toBe(200);saved=await r.json();await route.abort('failed');});
  await page.getByLabel('报告标题',{exact:true}).first().fill('D26 保存的 v1');
  await page.getByRole('button',{name:'保存第 1 版',exact:true}).click();
  await expect(page.getByRole('alert').filter({hasText:'保存结果未知'})).toBeVisible();
  await expect(page.getByRole('button',{name:'保存第 1 版',exact:true})).toBeDisabled();
  const unknownPrompt=await page.getByRole('alert').filter({hasText:'保存结果未知'}).innerText();
  await page.reload();
  await page.getByRole('button',{name:'查询历史操作（GET）',exact:true}).click();
  const article=page.getByRole('article',{name:'已保存报告版本'});
  await expect(article).toContainText('D26 保存的 v1');
  expect(writes.filter(w=>w.url.endsWith('/reports'))).toHaveLength(1);
  const current=await (await page.request.get('/api/__test__/d26-counts')).json();expect(current.report_revisions).toBe(1);
  const unsavedBefore=(await article.innerText()).includes('草稿尚未保存');expect(unsavedBefore).toBe(false);
  await page.getByRole('button',{name:'编辑为新版本',exact:true}).click();
  await page.getByLabel('报告标题',{exact:true}).fill('D26 保存的 v2');
  await expect(page.getByRole('status').filter({hasText:'当前编辑尚未保存'})).toBeVisible();
  await page.getByRole('button',{name:'保存为 v2',exact:true}).click();
  await expect(article).toContainText('D26 保存的 v2');await expect.poll(async()=>await article.innerText()).not.toContain('草稿尚未保存');
  const v2=await (await page.request.get(`/api/reports/${saved.report.report_id}/revisions/2`)).json();
  const v1=await (await page.request.get(`/api/reports/${saved.report.report_id}/revisions/1`)).json();
  expect(v1.report).toEqual(saved.report);
  await page.getByLabel('报告版本', { exact: true }).selectOption('1');await expect(article).toContainText('D26 保存的 v1');
  await page.goBack(); await expect(article).toContainText('D26 保存的 v2'); await expect(page.getByLabel('报告版本', { exact: true })).toHaveValue('2');
  await page.goForward(); await expect(article).toContainText('D26 保存的 v1'); await expect(page.getByLabel('报告版本', { exact: true })).toHaveValue('1');
  const before=await (await page.request.get('/api/__test__/d26-counts')).json();
  await page.route('**/api/reports?*',async route=>{const r=await route.fetch();expect(r.status()).toBe(200);await route.abort('failed');});
  await page.getByText('已保存报告历史',{exact:true}).click();
  await page.getByRole('button',{name:'刷新报告历史',exact:true}).click();
  await expect(page.getByRole('alert').filter({hasText:'报告历史读取失败'})).toBeVisible();
  const historyPrompt=await page.getByRole('alert').filter({hasText:'报告历史读取失败'}).innerText();
  await page.unroute('**/api/reports?*');await page.getByRole('button',{name:'刷新报告历史',exact:true}).click();
  expect(await (await page.request.get('/api/__test__/d26-counts')).json()).toEqual(before);
  const downloadEvent=page.waitForEvent('download');await page.getByRole('button',{name:'下载 v1 · Markdown',exact:true}).click();
  const download=await downloadEvent;await download.saveAs(`${out}/saved-v1.md`);
  expect(await download.failure()).toBeNull();
  const exportResponse=await page.request.get(`/api/reports/${saved.report.report_id}/revisions/1/markdown`);
  expect(exportResponse.ok()).toBe(true);expect(readFileSync(`${out}/saved-v1.md`)).toEqual(await exportResponse.body());
  expect(exportResponse.headers()['x-report-revision']).toBe('1');
  expect(await (await page.request.get('/api/__test__/d26-counts')).json()).toEqual(before);
  expect(writes.filter(w=>w.url.endsWith('/reports')||w.url.endsWith('/revisions'))).toHaveLength(2);
  await page.screenshot({path:`${out}/saved-status.png`,fullPage:true});
  writeFileSync(`${out}/report-fault-proof.json`,JSON.stringify({saved,v2,writes,unknownPrompt,historyPrompt,before,after:before,immutable_v1_exact:true,unsavedBefore,markdown_sha256:exportResponse.headers()['x-markdown-sha256'],human_acceptances:0,actual_model:false},null,2));
});
