"""Run this migration against real HTTP/PDF/SQLite with isolated simulated consent.

No credentials, production databases, real model, or vector provider are used.
The seed is generated by actual browser actions in this run, never inherited.
"""

import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import socket
import sqlite3
import subprocess
import sys
import tempfile
import time
from urllib.request import urlopen

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument("--out", type=Path, required=True)
parser.add_argument(
    "--extra",
    nargs="*",
    default=["ux-simplification-reading.spec.ts", "ux-simplification-dashboard.spec.ts"],
)
parser.add_argument("--journey-only", action="store_true")
args = parser.parse_args()
out = args.out.resolve()
out.mkdir(parents=True, exist_ok=False)
runtime = Path(tempfile.mkdtemp(prefix="findoc-d11-ux-simplification-")).resolve()
node = shutil.which("node")
if (
    not node
    or subprocess.check_output([node, "--version"], text=True).strip().split(".")[0] != "v24"
):
    raise RuntimeError("Node 24 must be on PATH")
sources = json.loads((root / "product/validation/sources.json").read_text())
for item in sources:
    path = root.parent / "findoc-analyst-v1-d9" / item["path"]
    if hashlib.sha256(path.read_bytes()).hexdigest() != item["sha256"]:
        raise RuntimeError("Source bytes do not match pinned SHA")
    item["absolute_path"] = str(path)
(out / "sources.json").write_text(json.dumps(sources, ensure_ascii=False, indent=2))
ports = []
for _ in range(2):
    with socket.socket() as sock:
        sock.bind(("127.0.0.1", 0))
        ports.append(sock.getsockname()[1])
api, web = f"http://127.0.0.1:{ports[0]}", f"http://127.0.0.1:{ports[1]}"
env = {k: v for k, v in os.environ.items() if not k.startswith("LLM_") and k != "OPENAI_API_KEY"}
env.update(
    FINDOC_UX_RUNTIME_ROOT=str(runtime),
    FINDOC_D21_RUNTIME_ROOT=str(runtime),
    FINDOC_D22_RUNTIME_ROOT=str(runtime),
    FINDOC_RUNTIME_ROOT=str(runtime),
    FINDOC_UX_LIVE="0",
    FINDOC_UX_INTEGRATION="1",
    FINDOC_E2E_DISABLE_ENV_FILES="1",
    FINDOC_API_ORIGIN=api,
    UX_ARTIFACT_DIR=str(out),
    UX_SOURCE_FILE=str(out / "sources.json"),
    D26_REPORT_SEED_DIR=str(out),
    PYTHONDONTWRITEBYTECODE="1",
    OMP_NUM_THREADS="1",
    MKL_NUM_THREADS="1",
    VECLIB_MAXIMUM_THREADS="1",
    HF_HUB_OFFLINE="1",
)
record = dict(
    runtime_root=str(runtime),
    actual_chromium=True,
    actual_http=True,
    actual_sqlite=True,
    actual_pdf=True,
    actual_llm=False,
    actual_bge=False,
    actual_milvus=False,
    simulated_test=True,
    human_acceptances=0,
    phases=[],
    servers_stopped=False,
)
handles, processes = [], []
code = 1
try:
    for name, command, cwd in [
        (
            "api",
            [
                sys.executable,
                "-m",
                "uvicorn",
                "tests.support.d26_app:create_app",
                "--factory",
                "--host",
                "127.0.0.1",
                "--port",
                str(ports[0]),
            ],
            root,
        ),
        (
            "web",
            [
                node,
                str(root / "frontend/node_modules/vite/bin/vite.js"),
                "--host",
                "127.0.0.1",
                "--port",
                str(ports[1]),
                "--strictPort",
            ],
            root / "frontend",
        ),
    ]:
        handle = (out / f"{name}.log").open("w")
        handles.append(handle)
        processes.append(
            subprocess.Popen(command, cwd=cwd, env=env, stdout=handle, stderr=subprocess.STDOUT)
        )
    for url in [api + "/companies", web]:
        deadline = time.monotonic() + 120
        while True:
            if any(p.poll() is not None for p in processes):
                raise RuntimeError("Server exited; see run logs")
            try:
                with urlopen(url, timeout=2) as response:
                    assert response.status == 200
                break
            except Exception:
                if time.monotonic() > deadline:
                    raise RuntimeError("Server startup timeout")
                time.sleep(0.25)
    phases = [("journey", ["ux-simplification-journey.spec.ts"])]
    if not args.journey_only and args.extra:
        phases.append(("reading", args.extra))
    for phase, specs in phases:
        config = root / f"frontend/test-results/{out.name}-{phase}.config.mjs"
        config.parent.mkdir(parents=True, exist_ok=True)
        config.write_text(
            'import {defineConfig} from "@playwright/test"; export default defineConfig('
            + json.dumps(
                dict(
                    testDir=str(root / "frontend/e2e"),
                    testMatch=specs,
                    workers=1,
                    retries=0,
                    timeout=180000,
                    reporter=[
                        ["line"],
                        ["json", {"outputFile": str(out / f"{phase}-results.json")}],
                    ],
                    outputDir=str(out / f"{phase}-traces"),
                    use=dict(
                        baseURL=web,
                        trace="retain-on-failure",
                        viewport=dict(width=1440, height=900),
                        actionTimeout=15000,
                    ),
                )
            )
            + ");"
        )
        code = subprocess.call(
            [
                node,
                str(root / "frontend/node_modules/@playwright/test/cli.js"),
                "test",
                "--config",
                str(config),
            ],
            cwd=root / "frontend",
            env=env,
        )
        record["phases"].append(dict(phase=phase, specs=specs, exit_code=code))
        if code:
            break
        if phase == "journey":
            # Capture a consistent seed before report tests add any revisions.
            # sqlite backup handles WAL and never mutates the live source.
            seed_root = Path(tempfile.mkdtemp(prefix="findoc-d11-ux-clean-seed-")).resolve()
            with sqlite3.connect(f"file:{runtime / 'documents.db'}?mode=ro", uri=True) as source_db:
                with sqlite3.connect(seed_root / "documents.db") as seed_db:
                    source_db.backup(seed_db)
                    assert seed_db.execute("SELECT count(*) FROM reports").fetchone()[0] == 0
            shutil.copytree(runtime / "objects", seed_root / "objects")
            result = json.loads((out / "journey-proof.json").read_text())["result"]
            (out / "report-test-proof.json").write_text(
                json.dumps({"runtime_root": str(seed_root), "cases": [{"result": result}]})
            )
            record["clean_seed_root"] = str(seed_root)
finally:
    for process in reversed(processes):
        process.terminate()
        try:
            process.wait(timeout=10)
        except subprocess.TimeoutExpired:
            process.kill()
            process.wait()
    for handle in handles:
        handle.close()
    record.update(exit_code=code, servers_stopped=all(p.poll() is not None for p in processes))
    (out / "record.json").write_text(json.dumps(record, indent=2))
    print(json.dumps(record), flush=True)
sys.exit(code)
